package com.darkp2p.protocol

import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * Frames produced by this implementation, for the web client to read
 * (`test/vectors/android-v3.json`, checked by `test/vectors.test.mjs`): the
 * handshake and one complete transfer, exactly as [RoomMachine] would send them.
 *
 * Regenerate with `./gradlew :protocol:test -PwriteVectors`.
 */
class AndroidVectorsTest {
    private val random = SeededRandom(20261126)

    private fun bytes(n: Int) = ByteArray(n).also(random::nextBytes)

    private fun build(): String {
        val roomKeyBytes = bytes(32)
        val initNonce = bytes(32)
        val respNonce = bytes(32)
        val room = RoomKey(roomKeyBytes)
        val keys = TransferKeyCache(room, SessionNonces(initNonce, respNonce), 64)
        val frames = ArrayList<JsonValue>()

        fun add(type: FrameType, role: Role, id: TransferId, seq: Long, payload: ByteArray, json: String?) {
            val key = if (type == FrameType.HELLO) FrameKeys.hello(room, id) else keys[id]
            val frame = FrameCodec.encode(type, role, id, seq, payload, key, bytes(12))
            frames += Json.obj(
                "type" to Json.num(type.wire.toLong()), "role" to Json.num(role.wire.toLong()), "transferId" to Json.str(id.hex),
                "seq" to Json.num(seq), "json" to json?.let(Json::str), "payload" to Json.str(Bytes.toHex(payload)),
                "frame" to Json.str(Bytes.toHex(frame)),
            )
        }
        fun ctrl(role: Role, id: TransferId, seq: Long, json: String) = add(FrameType.CTRL, role, id, seq, json.toByteArray(), json)
        fun id() = TransferId(bytes(16))
        val a = Role.INITIATOR
        val b = Role.RESPONDER

        // Handshake, both directions.
        // The hello offers chat, as the app sends it: the page must still accept it.
        Ctrl.hello(initNonce, listOf(Capabilities.CHAT)).let { add(FrameType.HELLO, a, id(), 0, it.toByteArray(), it) }
        Ctrl.hello(respNonce, listOf(Capabilities.CHAT)).let { add(FrameType.HELLO, b, id(), 0, it.toByteArray(), it) }
        ctrl(a, id(), 0, Ctrl.helloAck())
        ctrl(b, id(), 0, Ctrl.helloAck())

        // One transfer, initiator to responder: 70 chunks, so one mid-transfer ack.
        val chunkSizes = List(70) { if (it == 69) 37 else 100 }
        val size = chunkSizes.sum().toLong()
        val transfer = id()
        ctrl(a, transfer, 0, Ctrl.meta("från Android \"quoted\" \\ – 文件\u0001.bin", size, "application/x-test", 70))
        ctrl(b, transfer, 1, Ctrl.accept())
        chunkSizes.forEachIndexed { i, n -> add(FrameType.DATA, a, transfer, i + 1L, bytes(n), null) }
        ctrl(b, transfer, 2, Ctrl.ack(64))
        ctrl(a, transfer, 71, Ctrl.done(70, size))
        ctrl(b, transfer, 3, Ctrl.ack(70, final = true))
        ctrl(b, transfer, 4, Ctrl.complete())

        // The other endings.
        for (reason in DeclineReason.entries) id().let { t ->
            ctrl(b, t, 0, Ctrl.meta("declined", 1, "", 1))
            ctrl(a, t, 1, Ctrl.decline(reason))
        }
        for (reason in AbortReason.entries) id().let { t ->
            ctrl(a, t, 0, Ctrl.meta("aborted", 0, "", 0))
            ctrl(a, t, 1, Ctrl.abort(reason))
            ctrl(b, t, 1, Ctrl.abort(reason))
        }
        // A full-size chunk and the highest seq.
        add(FrameType.DATA, b, id(), 0xFFFF_FFFFL, bytes(WireConstants.CHUNK_SIZE), null)

        val lines = ArrayList<String>()
        lines += "{"
        lines += """ "format": "darkp2p/v3","""
        lines += """ "about": "Generated by android/protocol AndroidVectorsTest. Do not edit: run `./gradlew :protocol:test -PwriteVectors` in android/.","""
        lines += """ "roomKey": "${Bytes.toHex(roomKeyBytes)}","""
        lines += """ "initNonce": "${Bytes.toHex(initNonce)}","""
        lines += """ "respNonce": "${Bytes.toHex(respNonce)}","""
        lines += """ "transfer": {"transferId": "${transfer.hex}", "chunks": 70, "size": $size},"""
        lines += """ "frames": ["""
        frames.forEachIndexed { i, f -> lines += "  " + Json.stringify(f) + if (i == frames.size - 1) "" else "," }
        lines += " ]"
        lines += "}"
        return lines.joinToString("\n") + "\n"
    }

    @Test
    fun `android-v3 json is up to date`() {
        val file = File(System.getProperty("darkp2p.androidVectors") ?: error("darkp2p.androidVectors is not set"))
        val fresh = build()
        if (System.getProperty("darkp2p.writeVectors") == "true") file.writeText(fresh)
        assertEquals(fresh, file.readText(), "run ./gradlew :protocol:test -PwriteVectors")
        // It is valid JSON by this module's own strict parser, and every frame decodes.
        val root = Json.parse(fresh) as JsonValue.Obj
        assertEquals(4 + 6 + 70 + 6 + 12 + 1, root.arr("frames").size)
    }
}
